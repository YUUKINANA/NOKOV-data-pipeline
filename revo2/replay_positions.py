"""Replay processed 6-D hand controls to a REVO2 hand.

The input is the stable CSV generated by ``ml.process_hand_sessions``:
``controls_6d_stable.csv``. By default all six REVO2 channels are replayed.
Use ``--hold-thumb`` to keep the thumb fixed and replay only the other fingers.
"""

from __future__ import annotations

import argparse
import asyncio
import csv
import time
from dataclasses import dataclass
from pathlib import Path

from revo2.send_positions import (
    DEFAULT_BAUDRATE,
    DEFAULT_PORT,
    DEFAULT_SLAVE_ID,
    _baudrate_from_int,
    _close_client,
    _format_positions,
    _normalized_positions,
    _normalized_speed,
    stark,
)


PROJECT_ROOT = Path(__file__).resolve().parents[1]
PROCESSED_ROOT = PROJECT_ROOT / "data" / "processed"
DEFAULT_FALLBACK_POSITIONS = [400, 399, 50, 50, 50, 49]

CHANNEL_COLUMNS = {
    0: "command_thumb_flexion_0_1",
    1: "command_thumb_opposition_0_1",
    2: "command_index_flexion_0_1",
    3: "command_middle_flexion_0_1",
    4: "command_ring_flexion_0_1",
    5: "command_little_flexion_0_1",
}
THUMB_CHANNELS = {0, 1}


@dataclass(frozen=True)
class ReplayFrame:
    elapsed_s: float
    positions: list[int]


def _latest_controls_csv() -> Path:
    candidates = sorted(
        PROCESSED_ROOT.glob("mocap_*/controls_6d_stable.csv"),
        key=lambda path: path.stat().st_mtime,
    )
    if not candidates:
        raise FileNotFoundError(
            f"No controls_6d_stable.csv found under {PROCESSED_ROOT}"
        )
    return candidates[-1]


def _clip(value: int, low: int, high: int) -> int:
    return max(low, min(high, value))


def _read_float(row: dict[str, str], key: str) -> float | None:
    text = row.get(key, "").strip()
    if not text:
        return None
    return float(text)


def load_replay_frames(
    csv_path: Path,
    *,
    initial_positions: list[int],
    max_position: int,
    rate_hz: float,
    max_step: int,
    hold_thumb: bool,
) -> list[ReplayFrame]:
    if rate_hz <= 0:
        raise argparse.ArgumentTypeError("rate_hz must be positive.")
    if max_step <= 0:
        raise argparse.ArgumentTypeError("max_step must be positive.")

    csv_path = csv_path.resolve()
    frames: list[ReplayFrame] = []
    next_sample_s = 0.0
    previous = initial_positions.copy()

    with csv_path.open("r", encoding="utf-8-sig", newline="") as stream:
        reader = csv.DictReader(stream)
        missing_columns = [
            column
            for column in ("elapsed_s", *CHANNEL_COLUMNS.values())
            if column not in (reader.fieldnames or [])
        ]
        if missing_columns:
            raise ValueError(f"Missing columns in {csv_path}: {missing_columns}")

        for row in reader:
            elapsed_s = _read_float(row, "elapsed_s")
            if elapsed_s is None or elapsed_s + 1e-9 < next_sample_s:
                continue

            positions = previous.copy()
            if hold_thumb:
                positions[0] = initial_positions[0]
                positions[1] = initial_positions[1]

            for finger_index, column in CHANNEL_COLUMNS.items():
                if hold_thumb and finger_index in THUMB_CHANNELS:
                    continue

                normalized = _read_float(row, column)
                if normalized is None:
                    target = previous[finger_index]
                else:
                    target = round(_clip(round(normalized * 1000), 0, max_position))

                delta = _clip(target - previous[finger_index], -max_step, max_step)
                positions[finger_index] = previous[finger_index] + delta

            frames.append(ReplayFrame(elapsed_s=elapsed_s, positions=positions))
            previous = positions
            next_sample_s = elapsed_s + 1.0 / rate_hz

    if not frames:
        raise ValueError(f"No replayable rows found in {csv_path}")
    return frames


async def _read_current_positions(client, slave_id: int) -> list[int]:
    positions = await client.get_finger_positions(slave_id)
    return _normalized_positions([int(value) for value in list(positions)])


async def replay(
    *,
    csv_path: Path,
    port: str,
    baudrate: int,
    slave_id: int,
    speed: int,
    rate_hz: float,
    max_position: int,
    max_step: int,
    dry_run: bool,
    thumb: list[int] | None,
    start_positions: list[int] | None,
    hold_thumb: bool,
) -> None:
    speed = _normalized_speed(speed)
    max_position = _clip(int(max_position), 0, 1000)

    if dry_run:
        thumb_positions = thumb if thumb is not None else [0, 0]
        thumb_positions = _normalized_positions([*thumb_positions, 0, 0, 0, 0])[:2]
        frames = load_replay_frames(
            csv_path,
            initial_positions=[*thumb_positions, 0, 0, 0, 0],
            max_position=max_position,
            rate_hz=rate_hz,
            max_step=max_step,
            hold_thumb=hold_thumb,
        )
        print(f"CSV: {csv_path}")
        print(f"Frames to send: {len(frames)} at {rate_hz:g} Hz")
        print(f"Speed: {speed}, max_position: {max_position}, max_step: {max_step}")
        print(f"Mode: {'hold thumb' if hold_thumb else 'replay all six channels'}")
        if hold_thumb:
            print(f"Thumb held at: {thumb_positions} (dry-run placeholder)")
        print(f"First command: {_format_positions(frames[0].positions)}")
        print(f"Last command:  {_format_positions(frames[-1].positions)}")
        print("Dry run only. No serial connection was opened.")
        return

    client = await stark.modbus_open(port, _baudrate_from_int(baudrate))
    try:
        await client.set_finger_unit_mode(slave_id, stark.FingerUnitMode.Normalized)

        try:
            current = await _read_current_positions(client, slave_id)
        except Exception as exc:
            current = _normalized_positions(start_positions or DEFAULT_FALLBACK_POSITIONS)
            print(
                "[warn] failed to read current positions; "
                f"using fallback start positions: {_format_positions(current)} ({exc})"
            )
        thumb_positions = thumb if thumb is not None else current[:2]
        thumb_positions = _normalized_positions([*thumb_positions, 0, 0, 0, 0])[:2]
        initial_positions = _normalized_positions([*thumb_positions, *current[2:]])

        frames = load_replay_frames(
            csv_path,
            initial_positions=initial_positions,
            max_position=max_position,
            rate_hz=rate_hz,
            max_step=max_step,
            hold_thumb=hold_thumb,
        )

        print(f"CSV: {csv_path}")
        print(f"Frames to send: {len(frames)} at {rate_hz:g} Hz")
        print(f"Speed: {speed}, max_position: {max_position}, max_step: {max_step}")
        print(f"Mode: {'hold thumb' if hold_thumb else 'replay all six channels'}")
        if hold_thumb:
            print(f"Thumb held at: {thumb_positions}")
        print(f"First command: {_format_positions(frames[0].positions)}")
        print(f"Last command:  {_format_positions(frames[-1].positions)}")

        speeds = [speed] * 6
        start = time.perf_counter()
        first_elapsed = frames[0].elapsed_s
        for index, frame in enumerate(frames, start=1):
            target_time = start + (frame.elapsed_s - first_elapsed)
            wait_s = target_time - time.perf_counter()
            if wait_s > 0:
                await asyncio.sleep(wait_s)

            await client.set_finger_positions_and_speeds(
                slave_id, frame.positions, speeds
            )
            if index == 1 or index == len(frames) or index % max(1, int(rate_hz)) == 0:
                print(f"sent {index:04d}/{len(frames)}: {_format_positions(frame.positions)}")
    finally:
        await _close_client(client)


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Replay stable 6-D controls to REVO2."
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=None,
        help="Path to controls_6d_stable.csv. Default: latest processed mocap session.",
    )
    parser.add_argument("--port", default=DEFAULT_PORT, help="Serial port. Default: COM3.")
    parser.add_argument(
        "--baudrate",
        type=int,
        default=DEFAULT_BAUDRATE,
        help="Serial baudrate. Default: 460800.",
    )
    parser.add_argument(
        "--slave-id",
        type=int,
        default=DEFAULT_SLAVE_ID,
        help="Modbus device id. Default: 127.",
    )
    parser.add_argument(
        "--speed",
        type=_normalized_speed,
        default=250,
        help="REVO2 speed for all fingers, 0..1000. Default: 250.",
    )
    parser.add_argument(
        "--rate-hz",
        type=float,
        default=15.0,
        help="Replay send frequency. Default: 15.",
    )
    parser.add_argument(
        "--max-position",
        type=int,
        default=500,
        help="Safety cap for replayed channel commands. Default: 500.",
    )
    parser.add_argument(
        "--max-step",
        type=int,
        default=35,
        help="Maximum per-send change for each moving finger. Default: 35.",
    )
    parser.add_argument(
        "--thumb",
        nargs=2,
        type=int,
        metavar=("THUMB_FLEX", "THUMB_AUX"),
        help="Hold thumb at explicit positions. Implies --hold-thumb.",
    )
    parser.add_argument(
        "--hold-thumb",
        action="store_true",
        help="Keep thumb fixed and replay only index/middle/ring/pinky.",
    )
    parser.add_argument(
        "--start-positions",
        nargs=6,
        type=int,
        metavar="POS",
        help=(
            "Fallback initial positions when the current-position read fails. "
            "Default: 400 399 50 50 50 49."
        ),
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print replay summary without sending commands.",
    )
    return parser


def main() -> int:
    parser = build_parser()
    args = parser.parse_args()
    csv_path = args.csv or _latest_controls_csv()
    hold_thumb = bool(args.hold_thumb or args.thumb is not None)
    asyncio.run(
        replay(
            csv_path=csv_path,
            port=args.port,
            baudrate=args.baudrate,
            slave_id=args.slave_id,
            speed=args.speed,
            rate_hz=args.rate_hz,
            max_position=args.max_position,
            max_step=args.max_step,
            dry_run=args.dry_run,
            thumb=args.thumb,
            start_positions=args.start_positions,
            hold_thumb=hold_thumb,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
